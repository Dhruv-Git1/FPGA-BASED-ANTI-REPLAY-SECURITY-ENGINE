"""Generate rtl/font8x8_rom.v from the public-domain font8x8_basic.h.

Usage: python host/gen_font.py <path to font8x8_basic.h>

Source: https://github.com/dhepper/font8x8 (Daniel Hepper, public domain, based on
the public-domain IBM VGA fonts). In the source each byte is one pixel row and
bit 0 is the leftmost pixel. The SSD1306 OLED takes one byte per pixel column
with bit 0 at the top, so each glyph is transposed here.
Only printable ASCII (0x20 to 0x7E) is kept. Every other code draws blank.
"""

import re
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parents[1] / "rtl" / "font8x8_rom.v"


def parse(header: str) -> list[list[int]]:
    rows = re.findall(r"\{((?:\s*0x[0-9A-Fa-f]{2}\s*,?){8})\}", header)
    glyphs = [[int(b, 16) for b in re.findall(r"0x([0-9A-Fa-f]{2})", r)] for r in rows]
    if len(glyphs) != 128:
        sys.exit(f"Expected 128 glyphs, found {len(glyphs)}")
    return glyphs


def transpose(rows: list[int]) -> list[int]:
    # Column x byte: bit y is set when pixel (x, y) is on.
    return [sum(((rows[y] >> x) & 1) << y for y in range(8)) for x in range(8)]


def main() -> None:
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    glyphs = parse(Path(sys.argv[1]).read_text(encoding="utf-8"))
    lines = [
        "// Generated by host/gen_font.py from font8x8_basic.h. Do not edit by hand.",
        "// Font: https://github.com/dhepper/font8x8, public domain (IBM VGA font).",
        "// Returns one 8-pixel column of a character, bit 0 at the top, for the SSD1306.",
        "module font8x8_rom (",
        "    input  wire [6:0] ch,   // ASCII code",
        "    input  wire [2:0] col,  // column 0 (left) to 7",
        "    output reg  [7:0] bits",
        ");",
        "    always @(*) begin",
        "        case ({ch, col})",
    ]
    for code in range(0x20, 0x7F):
        cols = transpose(glyphs[code])
        label = chr(code) if chr(code) not in "\\" else "backslash"
        for x, byte in enumerate(cols):
            if byte:
                lines.append(f"            {{7'h{code:02X}, 3'd{x}}}: bits = 8'h{byte:02X};"
                             + (f"  // '{label}'" if x == 0 else ""))
    lines += [
        "            default: bits = 8'h00;",
        "        endcase",
        "    end",
        "endmodule",
        "",
    ]
    OUT.write_text("\n".join(lines), encoding="ascii", newline="\n")
    print(f"Wrote {OUT}")


if __name__ == "__main__":
    main()
